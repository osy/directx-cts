#!/usr/bin/env python3
"""Generate the WTTLog proxy's .def from what the kit binaries actually import.

    ./tools/gen_wttlog_def.py kit/WindowsKits10

CWTTLogger is a C++ class, so its exported names are MSVC-mangled and the mangling
differs by architecture (__thiscall "QAE" on x86, the uniform ABI "QEAA" elsewhere);
part of the surface is imported by ordinal.  Deriving the list from the kit keeps the
proxy from drifting away from it.

Result-bearing entry points are tapped, everything else is a loader forwarder to the
renamed original, which keeps varargs and the vtable exactly as Microsoft built them.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import pe as pemod  # noqa: E402

REAL_MODULE = "dxctswtt"   # the original, renamed at staging time
ARCHES = ["x64", "x86", "arm64"]

# Tapped because they carry the per-case verdict. Everything else forwards.
#
# Keyed by class-qualified name: the tap is declared with one method's signature, so
# matching on the bare method name would redirect a same-named method of some other
# exported class to a stub that reads its arguments wrongly.
TAPS = {
    "CWTTLogger::StartTestEx": "dxcts_start_test_ex",
    "CWTTLogger::EndTestEx": "dxcts_end_test_ex",
    "CWTTLogger::StartTest": "dxcts_start_test",
    "CWTTLogger::EndTest": "dxcts_end_test",
    "CWTTLogger::StartTestWithResID": "dxcts_start_test_resid",
    "CWTTLogger::EndTestWithResID": "dxcts_end_test_resid",
}

# The flat WTTLog* C entry points and the WTTLoggerCS*/WTTLoggerMBI* families also
# carry verdicts and are deliberately NOT tapped: their signatures are not recoverable
# from a decorated name the way a C++ method's are, and guessing one would corrupt the
# caller's stack on x86. A binary that logged through them would report every case as
# never run; none of the graphics content does.


def method_of(mangled: str) -> str | None:
    """`?Name@Class@@...` -> "Class::Name", for the members this taps."""
    if not mangled.startswith("?"):
        return None
    parts = mangled[1:].split("@")
    if len(parts) < 2 or not parts[1]:
        return None
    return f"{parts[1]}::{parts[0]}"


def collect(wttlog: Path) -> list[tuple[str, int]]:
    """(name, ordinal) for the whole export surface.

    The proxy re-exports everything rather than only what the test binaries import,
    because TAEF's logger delay-loads WTTLog and resolves part of it by ordinal:
    a partial proxy fails with "Failed to get the address of ordinal export 25".
    Ordinals are preserved for the same reason.
    """
    return sorted(((e.name, e.ordinal) for e in pemod.PEFile(wttlog).exports()
                   if e.name), key=lambda pair: pair[1])


def emit(exports: list[tuple[str, int]]) -> str:
    lines = [
        "; Generated by tools/gen_wttlog_def.py - do not edit.",
        ";",
        "; Forwarders target the original WTTLog, renamed to "
        f"{REAL_MODULE}.dll when staged.",
        "LIBRARY WTTLog",
        "EXPORTS",
    ]
    for name, ordinal in exports:
        method = method_of(name)
        tap = TAPS.get(method) if method else None
        target = tap if tap else f"{REAL_MODULE}.{name}"
        lines.append(f"    {name} = {target} @{ordinal}")
    return "\n".join(lines) + "\n"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    kit = Path(sys.argv[1])
    out_dir = Path(__file__).resolve().parent.parent / "src" / "shims" / "wttlog"
    for arch in ARCHES:
        wttlog = kit / "Testing" / "Runtimes" / "TAEF" / arch / "WTTLog.dll"
        if not wttlog.is_file():
            print(f"  skip {arch}: no {wttlog}")
            continue
        exports = collect(wttlog)
        tapped = sum(1 for name, _ in exports if method_of(name) in TAPS)
        (out_dir / f"wttlog-{arch}.def").write_text(emit(exports))
        print(f"  {arch}: {len(exports)} exports, {tapped} tapped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
