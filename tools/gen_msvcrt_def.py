#!/usr/bin/env python3
"""Generate the msvcrt forwarder's .def from what the kit binaries import from msvcrt.

    ./tools/gen_msvcrt_def.py kit/WindowsKits10

The x86 binaries - nearly every D3D9-era test, and the d3dx9/d3dx10 test helpers and
d3dref9 they load - import the /fp:precise SSE2 maths entry points
(_libm_sse2_cos_precise and so on), which Wine's msvcrt does not export: it has the
same functions only under their older __libm_sse2_* names, and no sqrt at all.  Each
of those binaries stops at start with "unimplemented function", before a case runs.

The forwarder is staged as dxmsvc.dll (the same length as msvcrt.dll, so the import name
can be rewritten in place).  The _precise names forward to Wine's __libm_sse2_*
equivalents, which take and return their doubles in xmm0 (pow's second operand in
xmm1) just as the _precise ones do; sqrt is implemented in msvcrt.c; everything else
the kit imports from msvcrt forwards straight back to msvcrt, so the process keeps one
CRT.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pe as pemod  # noqa: E402

KIT_ARCH = ("amd64", "x86", "arm64")
PREFIX, SUFFIX = "_libm_sse2_", "_precise"
# Wine's msvcrt has no __libm_sse2_sqrt to forward to.
IMPLEMENTED = {"_libm_sse2_sqrt_precise": "dxcts_libm_sse2_sqrt_precise"}


def collect(kit: Path) -> set[str]:
    names: set[str] = set()
    for arch in KIT_ARCH:
        tests = kit / "Hardware Lab Kit" / "Tests" / arch / "nttest" / "windowstest"
        for image in tests.rglob("*"):
            if image.suffix.lower() not in (".exe", ".dll"):
                continue
            try:
                imports = pemod.PEFile(image).all_imports()
            except pemod.NotPE:
                continue
            for imp in imports:
                if imp.dll.lower() == "msvcrt.dll":
                    names.update(fn for fn in imp.functions if isinstance(fn, str))
    return names


def target(name: str) -> str:
    if name in IMPLEMENTED:
        return IMPLEMENTED[name]
    if name.startswith(PREFIX) and name.endswith(SUFFIX):
        return "msvcrt.__libm_sse2_" + name[len(PREFIX):-len(SUFFIX)]
    return "msvcrt." + name


def emit(names: set[str]) -> str:
    lines = [
        "; Generated by tools/gen_msvcrt_def.py - do not edit.",
        ";",
        "; Every msvcrt import the kit makes, forwarded back to msvcrt - except the",
        "; _libm_sse2_*_precise maths entry points Wine lacks, which go to its",
        "; __libm_sse2_* equivalents (sqrt, which has none, is in msvcrt.c).",
        "LIBRARY dxmsvc",
        "EXPORTS",
    ]
    for name in sorted(names | set(IMPLEMENTED)):
        lines.append(f"    {name} = {target(name)}")
    lines += [
        "; The implementations' own names, which the compiler exports too.",
        *(f"    {impl}" for impl in sorted(IMPLEMENTED.values())),
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    names = collect(Path(sys.argv[1]))
    out = Path(__file__).resolve().parent.parent / "src" / "shims" / "msvcrt" / "msvcrt.def"
    out.write_text(emit(names))
    maths = sorted(n for n in names if n.startswith(PREFIX) and n.endswith(SUFFIX))
    print(f"  {len(names)} msvcrt imports, {len(maths)} _precise maths: {', '.join(maths)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
