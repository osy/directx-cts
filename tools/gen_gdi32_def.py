#!/usr/bin/env python3
"""Generate the gdi32 forwarder's .def from what the kit binaries import from gdi32.

    ./tools/gen_gdi32_def.py kit/WindowsKits10

The DXGI and D3D9-era binaries import D3DKMTOpenAdapterFromDeviceName,
D3DKMTQueryAdapterInfo and D3DKMTCloseAdapter from GDI32.dll directly rather than
through the api-ms-win-dx-d3dkmt apiset, so the d3dkmt shim - reached only by rewriting
the apiset name - never sees their calls, Wine's own answers empty the adapter
classification, and every one of them reports "AdapterType subset of size (0)".

The forwarder is staged as dxgdi.dll (the same length as GDI32.dll, so the import name
can be rewritten in place).  The D3DKMT entry points forward to the d3dkmt shim;
everything else the kit imports from gdi32 forwards straight back to gdi32.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pe as pemod  # noqa: E402

KMT_SHIM = "dxcts_d3dkmt_compat_shim_v1"

# Resolved with GetProcAddress rather than imported, so collect() cannot see them: the
# D3D9-era framework's version check loads L"gdi32.dll" - retargeted here at staging -
# and opens and closes the adapter of a display DC through these two.
BY_NAME = {"D3DKMTOpenAdapterFromHdc", "D3DKMTCloseAdapter"}
KIT_ARCH = ("amd64", "x86", "arm64")


def collect(kit: Path) -> set[str]:
    names: set[str] = set()
    for arch in KIT_ARCH:
        tests = kit / "Hardware Lab Kit" / "Tests" / arch / "nttest" / "windowstest"
        for image in tests.rglob("*"):
            if image.suffix.lower() not in (".exe", ".dll"):
                continue
            try:
                imports = pemod.PEFile(image).all_imports()
            except pemod.NotPE:
                continue
            for imp in imports:
                if imp.dll.lower() == "gdi32.dll":
                    names.update(fn for fn in imp.functions if isinstance(fn, str))
    return names


def kmt_shim_exports() -> set[str]:
    """What the d3dkmt shim actually exports; a D3DKMT name it lacks stays with gdi32,
    since a forwarder to a missing export would stop the importing binary loading."""
    definition = Path(__file__).resolve().parent.parent / "src" / "shims" / "d3dkmt" / "d3dkmt.def"
    return {line.strip() for line in definition.read_text().splitlines()
            if line.strip().startswith("D3DKMT")}


def emit(names: set[str]) -> str:
    shimmed = kmt_shim_exports()
    lines = [
        "; Generated by tools/gen_gdi32_def.py - do not edit.",
        ";",
        "; Every gdi32 import the kit makes, and the two its D3D9-era framework resolves",
        "; by name, forwarded back to gdi32 - except the",
        f"; D3DKMT adapter queries, which go to the d3dkmt shim ({KMT_SHIM}).",
        "LIBRARY dxgdi",
        "EXPORTS",
    ]
    for name in sorted(names):
        target = f"{KMT_SHIM}.{name}" if name in shimmed else f"gdi32.{name}"
        lines.append(f"    {name} = {target}")
    return "\n".join(lines) + "\n"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    names = collect(Path(sys.argv[1])) | BY_NAME
    out = Path(__file__).resolve().parent.parent / "src" / "shims" / "gdi32" / "gdi32.def"
    out.write_text(emit(names))
    kmt = sorted(names & kmt_shim_exports())
    print(f"  {len(names)} gdi32 imports, {len(kmt)} to the d3dkmt shim: {', '.join(kmt)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
