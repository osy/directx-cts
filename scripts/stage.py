#!/usr/bin/env python3
"""Assemble a self-contained staging directory a target can run from.

    ./scripts/stage.py --arch x64                  # -> staging/x64
    ./scripts/stage.py --arch x64 --no-rewrite     # skip the import rewrites

Everything lands flat, as HLK itself expects ("copy the support DLLs next to the
exe").  The kit is copied, never modified: rewrites are applied to the staging copy.

Copy this directory into a Wine bottle or a Windows VM and run dxcts.exe from it.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "tools"))

from hlkkit import DEFAULT_KIT_DIR, Fail, eprint  # noqa: E402
from shims import BACKENDS, SHIMS, behavioural, rewrites  # noqa: E402
import pe as pemod  # noqa: E402
from wineprefix import WinePrefix  # noqa: E402

PROJECT = Path(__file__).resolve().parent.parent

# Test-tree directory name per architecture.
KIT_ARCH = {"x64": "amd64", "x86": "x86", "arm64": "arm64"}
TAEF_ARCH = {"x64": "x64", "x86": "x86", "arm64": "arm64"}

# Copied flat into the staging root.  Tests resolve their support DLLs, data sources
# and media relative to their own directory.
FLATTEN = [
    "graphics/d3d/conf",
    "graphics/d3d/support",
    "graphics/d3d/api",
    "graphics/common",
    "graphics/web/dawn",
    "common",
]
FLATTEN_FILES = ["graphics/TDRWatch.exe"]


LAUNCHER = r"""#!/bin/sh
# Generated by stage.py.  Runs the suite with the host environment it needs.
#
# Metal aborts the process when a descriptor fails validation, on threads Wine cannot
# turn a signal into an exception on, so a group wedges for its whole timeout instead
# of reporting anything.  MTL_ERROR_MODE makes Metal report and return instead.  It
# has to be in the Unix environment before Wine starts, which is why this exists.
set -e
here=$(cd "$(dirname "$0")" && pwd)

MTL_ERROR_MODE=${MTL_ERROR_MODE-nslog}
export MTL_ERROR_MODE

# Where the host's own diagnostics go.  Metal and AGX write to the process's Unix
# fd 2, which every test process inherits from here - redirecting the child's Windows
# stderr does not move them, so the per-group .err files stay empty and these would
# otherwise just flood the terminal.  Naming the file lets the runner count what it
# survived and report it per group; the runner's progress stays on stdout.
DXCTS_HOST_LOG=${DXCTS_HOST_LOG-$here/dxcts-out/host-stderr.log}
export DXCTS_HOST_LOG
mkdir -p "$(dirname "$DXCTS_HOST_LOG")"
: > "$DXCTS_HOST_LOG"

# Inside a CrossOver bottle the bottle name and the C: path are both derivable from
# where this script was copied to, so neither has to be configured.
case $here in
*/Bottles/*/drive_c/*)
    bottle=${here#*/Bottles/}
    bottle=${bottle%%/drive_c/*}
    rest=${here#*/drive_c/}
    win="C:\\$(printf %s "$rest" | tr / '\\')"
    : "${WINE:=/Applications/CrossOver.app/Contents/SharedSupport/CrossOver/bin/wine}"
    exec "$WINE" --bottle "$bottle" --workdir "$win" --cx-app "$win\\dxcts.exe" "$@" 2>>"$DXCTS_HOST_LOG"
    ;;
esac

: "${WINE:=wine}"
cd "$here"
exec "$WINE" "$here/dxcts.exe" "$@" 2>>"$DXCTS_HOST_LOG"
"""


def copy_tree_flat(src: Path, dst: Path) -> int:
    if not src.is_dir():
        return 0
    count = 0
    for item in src.iterdir():
        target = dst / item.name
        if item.is_dir():
            shutil.copytree(item, target, dirs_exist_ok=True)
        else:
            shutil.copy2(item, target)
        count += 1
    return count


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--arch", default="x64", choices=["x64", "x86", "arm64"])
    ap.add_argument("--kit-dir", type=Path, default=DEFAULT_KIT_DIR)
    ap.add_argument("--build-dir", type=Path, default=None,
                    help="where the shims were built (default: build/<arch>/bin)")
    ap.add_argument("--out", type=Path, default=None,
                    help="staging directory (default: staging/<arch>)")
    ap.add_argument("--target", default="wine", choices=["wine", "windows"],
                    help="wine: stage every shim and rewrite imports where Wine "
                         "would fail to bind. windows: stage only the shims marked "
                         "every_target - the platform provides the rest, and a shim "
                         "in the application directory would shadow the real one "
                         "(default: wine)")
    ap.add_argument("--no-rewrite", action="store_true",
                    help="stage the shims but apply no import rewrites")
    args = ap.parse_args()

    kit = args.kit_dir / "WindowsKits10"
    if not kit.is_dir():
        raise Fail(f"no extracted kit at {kit}; run ./scripts/extract_kit.py")

    build = args.build_dir or PROJECT / "build" / args.arch / "bin"
    out = args.out or PROJECT / "staging" / args.arch
    tests = kit / "Hardware Lab Kit" / "Tests" / KIT_ARCH[args.arch] / "nttest" / "windowstest"
    taef = kit / "Testing" / "Runtimes" / "TAEF" / TAEF_ARCH[args.arch] / "MinTe"

    if not tests.is_dir():
        raise Fail(f"no test tree for {args.arch} at {tests}")
    if not taef.is_dir():
        raise Fail(f"no TAEF runtime at {taef}")

    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    for rel in FLATTEN:
        n = copy_tree_flat(tests / rel, out)
        eprint(f"  {n:4d} from {rel}")
    for rel in FLATTEN_FILES:
        src = tests / rel
        if src.is_file():
            shutil.copy2(src, out / src.name)

    # TAEF's MinTe drops managed-test hosting only; every native test DLL is covered.
    n = copy_tree_flat(taef, out)
    eprint(f"  {n:4d} from TAEF MinTe")

    staged_shims = []
    missing = []
    # every_target covers what is needed whatever the platform: the results channel,
    # and the shims a WARP run's adapter selection goes through.  Their own
    # workarounds are off by default on Windows; see src/common/knob.h.
    wanted = SHIMS if args.target == "wine" else [s for s in SHIMS if s.every_target]
    for shim in wanted:
        src = build / shim.module
        if not src.is_file():
            missing.append(shim.module)
            continue
        if shim.renames_original:
            original = out / shim.module
            if not original.is_file():
                raise Fail(f"{shim.module} is a proxy over the kit's own module, "
                           f"but {original} was not staged")
            original.replace(out / shim.renames_original)
        shutil.copy2(src, out / shim.module)
        staged_shims.append(shim)
    # Backend layers go on every target: which one a run applies is the runner's
    # --backend, and the file only has to be there for the shims to find.
    staged_backends = []
    for module in BACKENDS:
        src = build / module
        if not src.is_file():
            missing.append(module)
            continue
        shutil.copy2(src, out / module)
        staged_backends.append(module)
    if missing:
        raise Fail(f"shims not built for {args.arch} (looked in {build}):\n       "
                   + "\n       ".join(missing)
                   + f"\n\n       cmake -B build/{args.arch} -G Ninja \\\n"
                     f"         -DCMAKE_TOOLCHAIN_FILE=cmake/toolchains/windows.cmake \\\n"
                     f"         -DDXCTS_ARCH={args.arch} && cmake --build build/{args.arch}")

    runner = build / "dxcts.exe"
    if runner.is_file():
        shutil.copy2(runner, out / "dxcts.exe")
    else:
        eprint(f"  note: no dxcts.exe in {build}; staging the tests only")
    catalog = PROJECT / "suites"
    if catalog.is_dir():
        shutil.copytree(catalog, out / "suites", dirs_exist_ok=True)

    # Only the Wine target gets one: there is no Metal underneath on Windows.
    if args.target == "wine":
        launcher = out / "dxcts"
        launcher.write_text(LAUNCHER)
        launcher.chmod(0o755)

    applied: dict[str, list[str]] = {}
    if not args.no_rewrite:
        table = rewrites()
        # Only the Wine target asks what Wine can bind; on Windows every module
        # exists, so a shim staged there is one whose behaviour is wanted and its
        # rewrite is unconditional.
        wine = WinePrefix.find(args.arch) if args.target == "wine" else None
        shim_modules = {s.module for s in SHIMS}
        staged = {s.module for s in staged_shims}
        forced = behavioural()
        harness_of = {}
        for listing in (PROJECT / "suites").glob("*.jsonl"):
            for line in listing.read_text().splitlines():
                if line.strip().startswith("{"):
                    entry = json.loads(line)
                    if "binary" in entry:
                        harness_of[entry["binary"].lower()] = entry.get("harness")
        for image in sorted(out.glob("*")):
            if image.suffix.lower() not in (".exe", ".dll"):
                continue
            if image.name in shim_modules:
                continue
            try:
                imports = pemod.PEFile(image).all_imports()
            except pemod.NotPE:
                continue
            # Rewrite only where Wine would actually fail to bind the import, so a
            # binary is left untouched whenever the stock module already suffices.
            for imp in imports:
                target = table.get(imp.dll.lower())
                if target is None or target not in staged:
                    continue          # no shim for it, or not staged on this target
                if wine is not None:
                    host = wine.resolve(imp.dll)
                    available = wine.exports_of(host) if host else set()
                    binds = host and all(fn in available for fn in imp.functions)
                    if binds and not (forced.get(target, frozenset())
                                      & set(imp.functions)):
                        continue
                pemod.rewrite_import_name(image, imp.dll, target)
                applied.setdefault(target, []).append(image.name)

            # LoadLibrary on a string literal bypasses the import table entirely, so
            # those modules need the literal retargeted as well.
            for shim in SHIMS:
                if shim.module not in staged:
                    continue
                if not shim.loaded_by_name or not shim.replaces:
                    continue
                if (shim.literal_harness
                        and harness_of.get(image.name.lower()) != shim.literal_harness):
                    continue
                if pemod.rewrite_module_string(image, shim.replaces, shim.module):
                    key = shim.module + " (LoadLibrary)"
                    applied.setdefault(key, []).append(image.name)

    manifest = {
        "arch": args.arch,
        "target": args.target,
        "kit_version": json.loads((args.kit_dir / "fetch-manifest.json").read_text())
        ["kit_version"] if (args.kit_dir / "fetch-manifest.json").is_file() else None,
        "shims": [{"module": s.module, "replaces": s.replaces,
                   "renames_original": s.renames_original, "why": s.why}
                  for s in staged_shims],
        "backends": staged_backends,
        "rewrites": {k: sorted(v) for k, v in applied.items()},
        "launcher": "dxcts" if args.target == "wine" else None,
    }
    (out / "dxcts-staging.json").write_text(json.dumps(manifest, indent=2) + "\n")

    files = sum(1 for _ in out.rglob("*") if _.is_file())
    eprint(f"\nstaged {files} files -> {out}  (target: {args.target})")
    if staged_shims:
        eprint(f"shims: {', '.join(s.module for s in staged_shims)}")
    if staged_backends:
        eprint(f"backends: {', '.join(staged_backends)} (applied only with --backend)")
    else:
        eprint("shims: none (the target platform provides these modules itself)")
    if applied:
        for new, who in sorted(applied.items()):
            eprint(f"rewrote {len(who)} binaries -> {new}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
